import 'dart:io';
import 'dart:typed_data';
import 'package:crypto/crypto.dart';
import 'package:path_provider/path_provider.dart';

/// Persists document bytes (captured photos, generated PDFs) to the
/// app's local documents directory.
///
/// Files are content-addressed: the filename is the SHA-256 of the bytes
/// plus an extension sniffed from the content. That means any device can
/// find a file from the hash alone (which is what sync needs), the same
/// bytes are never stored twice, and no absolute paths ever cross the wire.
class DocumentStorage {
  DocumentStorage._();

  static final RegExp _hashPattern = RegExp(r'^[0-9a-f]{64}$');
  static const _extensions = ['.pdf', '.jpg', '.png', '.bin', ''];

  /// Hashes arrive over the network and become filenames, so they must be
  /// validated before touching the filesystem (no path traversal).
  static bool isValidHash(String? hash) =>
      hash != null && _hashPattern.hasMatch(hash);

  static Future<Directory> _documentsDir() async {
    final root = await getApplicationDocumentsDirectory();
    final dir = Directory('${root.path}/child_documents');
    if (!await dir.exists()) {
      await dir.create(recursive: true);
    }
    return dir;
  }

  static String hashOf(Uint8List bytes) => sha256.convert(bytes).toString();

  /// Saves locally captured/generated bytes. [filename] is kept for API
  /// compatibility with existing callers; storage is content-addressed.
  static Future<(String path, String sha256Hex)> save({
    required Uint8List bytes,
    String? filename,
  }) async {
    final hash = hashOf(bytes);
    return saveByHash(bytes: bytes, hash: hash);
  }

  /// Saves synced bytes under their hash. Throws [ArgumentError] if the
  /// bytes don't actually hash to [hash] (corrupt or tampered transfer).
  static Future<(String path, String sha256Hex)> saveByHash({
    required Uint8List bytes,
    required String hash,
  }) async {
    if (!isValidHash(hash)) {
      throw ArgumentError('Invalid document hash.');
    }
    if (hashOf(bytes) != hash) {
      throw ArgumentError('Document bytes do not match their hash.');
    }
    final existing = await localPathForHash(hash);
    if (existing != null) return (existing, hash);
    final dir = await _documentsDir();
    final file = File('${dir.path}/$hash${_extFor(bytes)}');
    await file.writeAsBytes(bytes, flush: true);
    return (file.path, hash);
  }

  static Future<bool> verify({
    required String path,
    required String expectedSha256,
  }) async {
    final file = File(path);
    if (!await file.exists()) return false;
    final bytes = await file.readAsBytes();
    return hashOf(bytes) == expectedSha256;
  }

  static Future<bool> hasBytesForHash(String hash) async {
    final path = await localPathForHash(hash);
    return path != null;
  }

  static Future<String?> localPathForHash(String hash) async {
    if (!isValidHash(hash)) return null;
    final dir = await _documentsDir();
    for (final ext in _extensions) {
      final file = File('${dir.path}/$hash$ext');
      if (await file.exists()) return file.path;
    }
    return null;
  }

  static Future<Uint8List?> readBytes(String path) async {
    final file = File(path);
    if (!await file.exists()) return null;
    return file.readAsBytes();
  }

  static String _extFor(Uint8List bytes) {
    if (bytes.length >= 4 &&
        bytes[0] == 0x25 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x44 &&
        bytes[3] == 0x46) {
      return '.pdf';
    }
    if (bytes.length >= 2 && bytes[0] == 0xFF && bytes[1] == 0xD8) {
      return '.jpg';
    }
    if (bytes.length >= 4 &&
        bytes[0] == 0x89 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x4E &&
        bytes[3] == 0x47) {
      return '.png';
    }
    return '.bin';
  }
}
